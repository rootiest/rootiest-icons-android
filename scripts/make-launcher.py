#!/usr/bin/env python3
"""make-launcher.py: write the launcher icon's vector drawables from rootiest-icons' rootiest-icons icon.

  scripts/make-launcher.py [ICONS_CHECKOUT]     default: $ROOTIEST_ICONS_DIR, then ~/projects/rootiest-icons

Writes app/src/main/res/drawable/ic_launcher_foreground.xml (the icon in its colors) and ic_launcher_monochrome.xml
(one color, for themed icons), from the full layout of icons/color/rootiest-icons.svg: the swirl and the emblem,
64 dp wide in the middle of the 108 dp canvas, inside the adaptive icon's safe zone.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICONS = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else
                           os.environ.get("ROOTIEST_ICONS_DIR") or "~/projects/rootiest-icons")
NAME = "rootiest-icons"


def main():
    svg = open(os.path.join(ICONS, "icons", "color", f"{NAME}.svg")).read()
    x, y, side, _ = (float(v) for v in re.search(r'viewBox="([^"]+)"', svg).group(1).split())
    colors = dict(re.findall(r"\.ColorScheme-(\w+)\{color:(#[0-9a-fA-F]{6})\}", svg.split("@media")[0]))
    full = re.search(r'\n  <g class="SizeFull">(.*?)\n  </g>', svg, re.S).group(1)
    logo = re.search(r'<path fill="currentColor" d="([^"]+)" class="ColorScheme-Accent"', full).group(1)
    tx, ty, s = (float(v) for v in re.search(r'transform="translate\(([-\d.]+) ([-\d.]+)\) scale\(([-\d.]+)\)"', full).groups())
    emblem = re.findall(r'\sd="([^"]+)"', full.split('class="ColorScheme-Emblem"', 1)[1])
    k = 64 / side
    for out, logo_color, emblem_color, what in (
            ("ic_launcher_foreground", colors["Accent"], colors["Emblem"], "The launcher icon's foreground, on mocha_base."),
            ("ic_launcher_monochrome", "#FFFFFF", "#FFFFFF", "The themed (monochrome) launcher icon.")):
        paths = "".join(f'\n            <path android:fillColor="#FF{emblem_color[1:].upper()}" android:pathData="{d}" />' for d in emblem)
        text = f"""<!-- {what} Generated by scripts/make-launcher.py from rootiest-icons icons/color/{NAME}.svg (the swirl and the emblem). -->
<!-- The swirl's long path is fine here: launchers draw the icon once and cache it. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:tools="http://schemas.android.com/tools" tools:ignore="VectorPath"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="{22 - x * k:.4f}" android:translateY="{22 - y * k:.4f}" android:scaleX="{k:.6f}" android:scaleY="{k:.6f}">
        <path android:fillColor="#FF{logo_color[1:].upper()}" android:pathData="{logo}" />
        <group android:translateX="{tx:g}" android:translateY="{ty:g}" android:scaleX="{s:g}" android:scaleY="{s:g}">{paths}
        </group>
    </group>
</vector>
"""
        path = os.path.join(HERE, "app", "src", "main", "res", "drawable", f"{out}.xml")
        open(path, "w").write(text)
        print(os.path.relpath(path, HERE))


if __name__ == "__main__":
    main()
